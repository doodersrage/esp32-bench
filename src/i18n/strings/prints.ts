export type PrintsKey = keyof typeof PRINTS_UI.en;

/** A catalog entry's text, falling back to the shared board case text. */
export function printText(t: Translate<typeof PRINTS_UI.en>, field: "name" | "sum" | "hw" | "note" | "replace", id: string): string {
  const own = `${field}.${id}` as PrintsKey;
  if (own in PRINTS_UI.en) return t(own);
  if ((field === "hw" || field === "note") && id.startsWith("case-")) return t(`${field}.case` as PrintsKey);
  return "";
}

/** A part maker parameter's label: param.<part>.<key>, else param.<key>. */
export function paramLabel(t: Translate<typeof PRINTS_UI.en>, part: string, key: string): string {
  const own = `param.${part}.${key}` as PrintsKey;
  return own in PRINTS_UI.en ? t(own) : t(`param.${key}` as PrintsKey);
}

export const printsTranslator = (locale: string | undefined) => translator(PRINTS_UI, locale);
