/** Translate a piece of English tool-card text from src/data/tools.ts; anything unknown stays as it is. */
export function toolText(english: string, locale: string | undefined): string {
  const key = (Object.keys(TOOL_DATA.en) as (keyof typeof TOOL_DATA.en)[]).find((k) => TOOL_DATA.en[k] === english);
  return key ? translator(TOOL_DATA, locale)(key) : english;
}

/**
 * Messages built in English by a library (src/lib/*): match the English text
 * against patterns with named groups and fill a translated string with them.
 * Unknown text is returned unchanged.
 */
export type Pattern<K extends string> = [RegExp, K];
export function byPattern<K extends string>(text: string, patterns: Pattern<K>[], t: Translate<Record<K, string>>): string {
  for (const [re, key] of patterns) {
    const m = re.exec(text);
    if (m) return t(key, m.groups ?? {});
  }
  return text;
}

