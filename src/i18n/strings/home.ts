import type { DrawerPart, Project, Tag } from "../../data/projects";

type Other = Exclude<Locale, "en">;

/** Look a data label up by id; English, or an id with no translation, gives the English text back. */
export function dataLabel<K extends string>(table: Record<Other, Partial<Record<K, string>>>, current: string | undefined) {
  const locale = localeOf(current);
  return (id: K, english: string): string => (locale === "en" ? english : (table[locale][id] ?? english));
}

