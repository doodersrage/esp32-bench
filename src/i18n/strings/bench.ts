type CrashKey = keyof (typeof CRASH)["en"] & string;

/** A crash hint from src/lib/crash.ts in the page's language. Unknown hints come back in English. */
export function crashHint(h: { key: string; text: string }, locale: Locale | string | undefined): string {
  const l = localeOf(locale);
  if (l === "en") return h.text;
  const t = translator(CRASH, l);
  const has = (k: string): k is CrashKey => k in CRASH.en;
  if (h.key === "backtrace") {
    const cmd = /addr2line .*$/.exec(h.text)?.[0];
    return cmd ? t("backtrace", { cmd }) : h.text;
  }
  if (h.key.startsWith("panic-")) {
    const m = /^Crash on core (\d+): (.+?)\. /.exec(h.text);
    return m && has(h.key) ? t("crashOn", { core: m[1], panic: m[2], why: t(h.key) }) : h.text;
  }
  if (h.key.startsWith("rst-") && has(h.key)) {
    const name = h.key.slice(4);
    return h.text.startsWith(`${name}: `) ? t("reset", { name, why: t(h.key) }) : t(h.key);
  }
  return has(h.key) ? t(h.key) : h.text;
}

