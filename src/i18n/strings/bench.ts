// Several texts here come from data and lib files that stay English. They are
// translated at display time: by their key (crash hints), or by looking up
// their exact English text (serial messages, pin rules, part notes).
import { defineStrings, translator, type Strings } from "../t";
import { localeOf, type Locale } from "../locales";

type Dict = Record<string, string>;

/** Translate a text that is one of `strings.en`'s values, by finding its key. Unknown text comes back unchanged. */
export function byEnglish<T extends Dict>(strings: Strings<T>, text: string, locale: string | undefined): string {
  const l = localeOf(locale);
  if (l === "en") return text;
  const en = strings.en as Dict;
  const key = Object.keys(en).find((k) => en[k] === text);
  return key ? ((strings[l] as Dict)[key] ?? text) : text;
}

