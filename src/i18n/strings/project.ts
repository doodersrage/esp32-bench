/** Fill a "... {link} ..." string around a DOM node, for browser scripts. */
export function withNode(text: string, node: Node): (string | Node)[] {
  const at = text.indexOf("{link}");
  return at < 0 ? [text] : [text.slice(0, at), node, text.slice(at + 6)];
}
