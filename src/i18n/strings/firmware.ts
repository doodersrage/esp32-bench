export type FirmwareKey = keyof typeof FIRMWARE.en;
type T = Translate<typeof FIRMWARE.en>;

/** A setting's label and hint in the page's language, falling back to the data's English. */
export function settingText(t: T, s: { key: string; label: string; hint?: string }): { label: string; hint?: string } {
  const has = (k: string): k is FirmwareKey => k in FIRMWARE.en;
  const labelKey = `set_${s.key}`;
  const hintKey = `hint_${s.key}`;
  return {
    label: has(labelKey) ? t(labelKey) : s.label,
    ...(s.hint !== undefined ? { hint: has(hintKey) ? t(hintKey) : s.hint } : {}),
  };
}

// English messages that come from src/lib, recognised by their wording.
const LIB_KEYS: FirmwareKey[] = [
  "noWebSerial",
  "libSketchEmpty",
  "libSketchTooBig",
  "libSetupLoop",
  "libBuildLimit",
  "libStartingUp",
  "libRefused",
  "libFailedLog",
  "libWaking",
  "libBuilding",
  "libNotAllowed",
  "libPickerFail",
  "libPortFail",
  "libNoBoard",
  "libBadName",
  "libNoTabs",
  "libMaxChars",
  "libWrongChip",
];
const LIB_PATTERNS = LIB_KEYS.map((key) => {
  const names: string[] = [];
  const source = FIRMWARE.en[key]
    .split(/\{(\w+)\}/)
    .map((part, i) => {
      if (i % 2) {
        names.push(part);
        return "(.+?)";
      }
      return part.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");
    })
    .join("");
  return { key, names, re: new RegExp(`^${source}$`, "s") };
});

/** Translate a message from src/lib if it is one we know; anything else (server text, browser errors) stays as is. */
export function fromLib(t: T, message: string): string {
  for (const { key, names, re } of LIB_PATTERNS) {
    const m = re.exec(message);
    if (m) return t(key, Object.fromEntries(names.map((n, i) => [n, m[i + 1]])));
  }
  return message;
}

/** Split a translated sentence on {name} placeholders and put the given nodes in their place. */
export function withNodes(text: string, nodes: Record<string, Node>): (string | Node)[] {
  return text
    .split(/\{(\w+)\}/)
    .map((part, i) => (i % 2 ? (nodes[part] ?? `{${part}}`) : part))
    .filter((p) => p !== "");
}
