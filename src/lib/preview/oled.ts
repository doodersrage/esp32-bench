/** The degree sign, which the sketches print with the font's code page 437 character 248. */
const DEGREE = [0x00, 0x06, 0x09, 0x09, 0x06];
/** Lower-case letters with descenders use the 8th row, as in Adafruit GFX's built-in font. */
const DESCENDERS: Record<string, number[]> = {
  g: [0x18, 0xa4, 0xa4, 0xa4, 0x7c],
  j: [0x40, 0x80, 0x84, 0x7d, 0x00],
  p: [0xfc, 0x24, 0x24, 0x24, 0x18],
  q: [0x18, 0x24, 0x24, 0x18, 0xfc],
  y: [0x9c, 0xa0, 0xa0, 0xa0, 0x7c],
};

/** The five column bytes for a character; unknown characters show as a box. */
export function glyph(ch: string): number[] {
  if (ch === "°") return DEGREE;
  if (DESCENDERS[ch]) return DESCENDERS[ch];
  const c = ch.charCodeAt(0);
  if (c < 0x20 || c > 0x7e) return [0x7f, 0x41, 0x41, 0x41, 0x7f];
  const at = (c - 0x20) * 5;
  return FONT.slice(at, at + 5);
}

export class Framebuffer {
  readonly pixels = new Uint8Array(OLED_W * OLED_H);
  cursorX = 0;
  cursorY = 0;
  textSize = 1;

  clear(): void {
    this.pixels.fill(0);
    this.cursorX = 0;
    this.cursorY = 0;
  }

  pixel(x: number, y: number, on = true): void {
    x = Math.floor(x);
    y = Math.floor(y);
    if (x < 0 || y < 0 || x >= OLED_W || y >= OLED_H) return;
    this.pixels[y * OLED_W + x] = on ? 1 : 0;
  }

  get(x: number, y: number): boolean {
    return x >= 0 && y >= 0 && x < OLED_W && y < OLED_H && this.pixels[y * OLED_W + x] === 1;
  }

  fillRect(x: number, y: number, w: number, h: number, on = true): void {
    for (let j = 0; j < h; j++) for (let i = 0; i < w; i++) this.pixel(x + i, y + j, on);
  }

  hline(x: number, y: number, w: number): void {
    this.fillRect(x, y, w, 1);
  }

  vline(x: number, y: number, h: number): void {
    this.fillRect(x, y, 1, h);
  }

  drawRect(x: number, y: number, w: number, h: number): void {
    this.hline(x, y, w);
    this.hline(x, y + h - 1, w);
    this.vline(x, y, h);
    this.vline(x + w - 1, y, h);
  }

  /** Rounded rectangle outline, like GFX drawRoundRect. */
  drawRoundRect(x: number, y: number, w: number, h: number, r: number): void {
    this.hline(x + r, y, w - 2 * r);
    this.hline(x + r, y + h - 1, w - 2 * r);
    this.vline(x, y + r, h - 2 * r);
    this.vline(x + w - 1, y + r, h - 2 * r);
    // Quarter circles in the corners (midpoint circle).
    let f = 1 - r, dx = 1, dy = -2 * r, px = 0, py = r;
    while (px < py) {
      if (f >= 0) {
        py--;
        dy += 2;
        f += dy;
      }
      px++;
      dx += 2;
      f += dx;
      const cx0 = x + r, cx1 = x + w - r - 1, cy0 = y + r, cy1 = y + h - r - 1;
      for (const [ax, ay] of [[px, py], [py, px]]) {
        this.pixel(cx1 + ax, cy0 - ay);
        this.pixel(cx0 - ax, cy0 - ay);
        this.pixel(cx1 + ax, cy1 + ay);
        this.pixel(cx0 - ax, cy1 + ay);
      }
    }
  }

  fillCircle(cx: number, cy: number, r: number): void {
    for (let y = -r; y <= r; y++) for (let x = -r; x <= r; x++) if (x * x + y * y <= r * r + r) this.pixel(cx + x, cy + y);
  }

  /** Draw one character at a size, as GFX does: 6 x 8 cells scaled by `size`. */
  drawChar(x: number, y: number, ch: string, size = 1): void {
    const cols = glyph(ch);
    for (let i = 0; i < 5; i++) {
      for (let j = 0; j < 8; j++) {
        if ((cols[i] >> j) & 1) this.fillRect(x + i * size, y + j * size, size, size);
      }
    }
  }

  setCursor(x: number, y: number): void {
    this.cursorX = x;
    this.cursorY = y;
  }

  /** print(): text at the cursor, wrapping on "\n" like GFX. */
  print(text: string | number): void {
    for (const ch of String(text)) {
      if (ch === "\n") {
        this.cursorX = 0;
        this.cursorY += 8 * this.textSize;
        continue;
      }
      this.drawChar(this.cursorX, this.cursorY, ch, this.textSize);
      this.cursorX += 6 * this.textSize;
    }
  }

  println(text: string | number = ""): void {
    this.print(`${text}\n`);
  }

  /** Width in pixels of text at a size (6 per character). */
  static textWidth(text: string, size = 1): number {
    return [...text].length * 6 * size;
  }

  invert(): void {
    for (let i = 0; i < this.pixels.length; i++) this.pixels[i] ^= 1;
  }

  /** Number of lit pixels, for tests. */
  litCount(): number {
    let n = 0;
    for (const p of this.pixels) n += p;
    return n;
  }
}
